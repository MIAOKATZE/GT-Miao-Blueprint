package com.miaokatze.gtmb.hologram;

import java.io.IOException;
import java.lang.reflect.Field;
import java.lang.reflect.Modifier;
import java.lang.reflect.ParameterizedType;
import java.lang.reflect.Type;
import java.util.Collection;
import java.util.LinkedHashMap;
import java.util.Map;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.miaokatze.gtmb.blueprint.editor.AuthorDocument;
import com.miaokatze.gtmb.blueprint.editor.AuthorDocumentIO;
import com.miaokatze.gtmb.blueprint.editor.AuthorSourceImporter;

/**
 * Preflight for the existing typed server save transport, not for lossless author recovery/export. Unknown JSON
 * extensions cannot survive that transport. Refuse before activation or overwrite rather than silently dropping them.
 * Structural inspection only: no registry, native provider, NBT decoding, world access or source mutation.
 */
public final class HologramAuthorFormalSaveCompatibility {

    private static final java.util.concurrent.ConcurrentMap<Class<?>, Map<String, Field>> RECORD_FIELDS =
        new java.util.concurrent.ConcurrentHashMap<>();

    private HologramAuthorFormalSaveCompatibility() {}

    public static void requireCompatible(byte[] source) throws IOException {
        if (source == null || source.length > HologramBlueprintArtifact.MAX_JSON_BYTES)
            throw new IOException("正式保存源超过格式预算；原稿保留");
        requireCompatible(AuthorSourceImporter.read(source, AuthorDocumentIO.Limits.defaults()));
    }

    public static void requireCompatible(AuthorDocument source) throws IOException {
        if (source == null) throw new IOException("缺少正式保存源；原稿保留");
        JsonObject root = source.sourceCopy();
        if (root.has("blueprint")) {
            for (Map.Entry<String, JsonElement> entry : root.entrySet()) {
                String key = entry.getKey();
                if ("blueprint".equals(key)) continue;
                // These established transport/presentation members are intentionally regenerated by a formal save.
                if ("schema".equals(key) || "owner".equals(key) || "uploadedBy".equals(key)) {
                    if (!entry.getValue().isJsonNull() && !entry.getValue().isJsonPrimitive()) reject("source/" + key);
                } else if ("previewBinding".equals(key)) {
                    binding(entry.getValue());
                } else reject("source/" + key);
            }
            inspect(root.get("blueprint"), HologramPresets.Preset.class, "blueprint");
        } else inspect(root, HologramPresets.Preset.class, "blueprint");
    }

    private static void binding(JsonElement value) throws IOException {
        if (value == null || !value.isJsonObject()) reject("source/previewBinding");
        for (Map.Entry<String, JsonElement> field : value.getAsJsonObject().entrySet()) {
            if (!("version".equals(field.getKey()) || "pngSha256".equals(field.getKey()))
                || !field.getValue().isJsonPrimitive()) reject("source/previewBinding/" + field.getKey());
        }
    }

    private static void inspect(JsonElement value, Type type, String path) throws IOException {
        // Known nullable fields retain their established native normalization semantics. Unknown null fields are
        // still rejected below: their names are extension data even when their value happens to be null.
        if (value == null || value.isJsonNull()) return;
        if (type instanceof ParameterizedType) {
            ParameterizedType parameterized = (ParameterizedType) type;
            Class<?> raw = (Class<?>) parameterized.getRawType();
            Type[] arguments = parameterized.getActualTypeArguments();
            if (Map.class.isAssignableFrom(raw)) {
                if (!value.isJsonObject()) reject(path);
                for (Map.Entry<String, JsonElement> field : value.getAsJsonObject().entrySet())
                    inspect(field.getValue(), arguments[1], path + "/" + field.getKey());
                return;
            }
            if (Collection.class.isAssignableFrom(raw)) {
                if (!value.isJsonArray()) reject(path);
                int index = 0;
                for (JsonElement member : value.getAsJsonArray()) inspect(member, arguments[0], path + "/" + index++);
                return;
            }
            reject(path);
        }
        if (!(type instanceof Class<?>)) reject(path);
        Class<?> record = (Class<?>) type;
        if (record.isPrimitive() || record == String.class || record == Boolean.class
            || Number.class.isAssignableFrom(record) || record.isEnum()) {
            if (!value.isJsonPrimitive()) reject(path);
            return;
        }
        if (!value.isJsonObject()) reject(path);
        Map<String, Field> fields = RECORD_FIELDS.computeIfAbsent(record, typeClass -> {
            Map<String, Field> declared = new LinkedHashMap<>();
            for (Field field : typeClass.getDeclaredFields())
                if (!Modifier.isStatic(field.getModifiers()) && !Modifier.isTransient(field.getModifiers())
                    && !field.isSynthetic()) declared.put(field.getName(), field);
            return java.util.Collections.unmodifiableMap(declared);
        });
        for (Map.Entry<String, JsonElement> entry : value.getAsJsonObject().entrySet()) {
            String child = path + "/" + entry.getKey();
            // Existing author-only completeness is a known UI fact, explicitly not portable authority.
            if (record == HologramPresets.Cell.class && "authorDeclarationComplete".equals(entry.getKey())) {
                if (!entry.getValue().isJsonNull() && (!entry.getValue().isJsonPrimitive()
                    || !entry.getValue().getAsJsonPrimitive().isBoolean())) reject(child);
                continue;
            }
            Field field = fields.get(entry.getKey());
            if (field == null) reject(child);
            inspect(entry.getValue(), field.getGenericType(), child);
        }
    }

    private static void reject(String path) throws IOException {
        throw new IOException("正式保存暂不支持保真传输扩展字段 " + path + "；未覆盖原成品，请保留恢复草稿或导出候选");
    }
}
